/**
 * Content and navigation checks for the presentation lane.
 * Run after bundling the check (see the command in the file header of build-preview)
 * or: node --experimental-strip-types is not required; esbuild bundles this file.
 */
import { readFileSync, existsSync, statSync } from "node:fs";
import { resolve } from "node:path";
import assert from "node:assert/strict";
import { actionFor, advance, openingReveal, retreat, FLIGHT_KEYS } from "./nav";
import { CORE_SLIDE_IDS, CREDIT, EVIDENCE_GAPS, MOTTO, SLIDES } from "./slides";

const root = process.cwd();
const read = (path: string) => readFileSync(resolve(root, path), "utf8");

const readme = read("README.md");
const story = read("docs/presentation/story.md");
const deckSource = read("components/presentation/Deck.tsx");
const fixture = read("components/presentation/motion-fixture.ts");

assert.deepEqual(
  SLIDES.filter((slide) => slide.part === "core").map((slide) => slide.id),
  [...CORE_SLIDE_IDS],
);
assert.equal(CORE_SLIDE_IDS.length, 8);
assert.deepEqual(
  SLIDES.filter((slide) => slide.part === "appendix").map((slide) => slide.id),
  ["sources", "orbit", "excluded", "evidence"],
);
assert.equal(new Set(SLIDES.map((slide) => slide.id)).size, SLIDES.length);

for (const slide of SLIDES) {
  assert.ok(slide.title.trim(), slide.id);
  assert.ok(slide.kicker.trim(), slide.id);
  assert.ok(slide.beats.length > 0, slide.id);
  assert.ok(slide.notes.length > 0, slide.id);
  for (const beat of slide.beats) assert.ok(beat.text.trim(), beat.id);
  assert.ok(story.includes(slide.title), `story missing ${slide.title}`);
}

const joined = [
  readme,
  story,
  ...SLIDES.flatMap((slide) => [slide.title, ...slide.beats.map((beat) => beat.text), ...slide.notes]),
].join("\n");

const banned: RegExp[] = [
  /\{\{TODO/,
  /XAI_API_KEY\s*=/,
  /NEXT_PUBLIC_XAI/,
  /three stars/i,
  /participation star/i,
  /\b70\s*seconds\b/i,
  /115 seconds/i,
  /thrust-to-weight/i,
  /\b379\b/,
  /youtube/i,
  /generated by/i,
  /co-authored-by/i,
  /lifts off/i,
];
for (const pattern of banned) assert.equal(pattern.test(joined), false, pattern.source);

for (const line of [MOTTO, CREDIT.authors, CREDIT.disclaimer, CREDIT.modelName, CREDIT.modelBy, CREDIT.licence]) {
  assert.ok(readme.includes(line), line);
  assert.ok(story.includes(line), `story ${line}`);
  assert.ok(deckSource.includes("CREDIT"), "deck renders the credit constant");
}

assert.match(readme, /not built/i);
assert.match(readme, /Placeholder/);
assert.ok(readme.includes("docs/presentation/teardown.pdf"));
assert.ok(readme.includes("public/presentation/index.html"));
assert.ok(readme.includes("/presentation"));
for (const gap of EVIDENCE_GAPS) assert.ok(readme.includes(gap), gap);
assert.equal(/cla(ude)|co(dex)/i.test(readme), false);

assert.match(fixture, /LOCAL FIXTURE/);
assert.match(fixture, /0\.15/);
assert.match(fixture, /0\.5/);
assert.match(fixture, /0\.75/);

for (const key of FLIGHT_KEYS) assert.equal(actionFor(key), null, key);
assert.equal(actionFor("ArrowRight"), "advance");
assert.equal(actionFor(" "), "advance");
assert.equal(actionFor("n"), "notes");
assert.equal(actionFor("f"), "fullscreen");
assert.equal(actionFor("Escape"), "close");
assert.equal(actionFor("M"), null);

const counts = [3, 2];
assert.deepEqual(advance({ index: 0, reveal: 1 }, counts, false), { index: 0, reveal: 2 });
assert.deepEqual(advance({ index: 0, reveal: 3 }, counts, false), { index: 1, reveal: 1 });
assert.deepEqual(advance({ index: 1, reveal: 2 }, counts, false), { index: 1, reveal: 2 });
assert.deepEqual(advance({ index: 0, reveal: 1 }, counts, true), { index: 1, reveal: 2 });
assert.deepEqual(retreat({ index: 0, reveal: 2 }, counts, false), { index: 0, reveal: 1 });
assert.deepEqual(retreat({ index: 1, reveal: 1 }, counts, false), { index: 0, reveal: 3 });
assert.deepEqual(retreat({ index: 0, reveal: 1 }, counts, false), { index: 0, reveal: 1 });
assert.equal(openingReveal(4, true, false), 4);
assert.equal(openingReveal(4, false, true), 4);
assert.equal(openingReveal(4, false, false), 1);

const explore = SLIDES.find((slide) => slide.id === "explore");
if (!explore) throw new Error("missing explore slide");
assert.equal(explore.figure, "explore");

const pdfDocs = resolve(root, "docs/presentation/teardown.pdf");
const pdfPublic = resolve(root, "public/presentation/teardown.pdf");
assert.ok(existsSync(pdfDocs), "docs PDF");
assert.ok(existsSync(pdfPublic), "public PDF");
assert.ok(statSync(pdfDocs).size > 10_000, "pdf looks empty");
assert.equal(statSync(pdfDocs).size, statSync(pdfPublic).size);

const pdf = readFileSync(pdfDocs);
const pages = pdf.toString("latin1").match(/\/Type\s*\/Page\b/g)?.length ?? 0;
assert.equal(pages, SLIDES.length, `pdf pages ${pages}`);

for (const file of [
  "docs/media/illustration-title.svg",
  "docs/media/placeholder-explore.svg",
  "docs/media/placeholder-replay.svg",
  "docs/media/placeholder-mission.svg",
  "docs/media/placeholder-phone.svg",
  "docs/media/placeholder-demo.svg",
]) {
  assert.ok(existsSync(resolve(root, file)), file);
  assert.match(read(file), /Placeholder|ILLUSTRATION/i);
}

const offline = read("public/presentation/index.html");
assert.match(offline, /deck\.js/);
assert.match(offline, /deck\.css/);
assert.ok(existsSync(resolve(root, "public/presentation/deck.js")));

console.log(`PASS presentation: ${SLIDES.length} slides, PDF ${pages} pages`);
