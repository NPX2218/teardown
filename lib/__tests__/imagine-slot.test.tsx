import { renderToStaticMarkup } from "react-dom/server";
import { beforeEach, describe, expect, it } from "vitest";
import { ImagineSlot } from "@/components/imagine/ImagineSlot";
import { cancelImagine, getImagineStatus } from "@/lib/imagine/client";
import { getImagineScene, patchImagineScene, resetImagineScene } from "@/lib/imagine/scene";

describe("imagine slot", () => {
  beforeEach(() => {
    resetImagineScene();
    cancelImagine();
  });

  it("shows Show in action for a selected part outside flight", () => {
    patchImagineScene({ selectedId: "legs", flightActive: false });
    const html = renderToStaticMarkup(<ImagineSlot />);
    expect(html).toContain("Show in action");
    expect(html).toContain('data-slot="imagine"');
    expect(html).not.toContain("Generated by Grok Imagine");
  });

  it("hides the button during flight replay or your mission", () => {
    patchImagineScene({ selectedId: "legs", flightActive: true });
    const html = renderToStaticMarkup(<ImagineSlot />);
    expect(html).not.toContain("Show in action");
  });

  it("shows a picture only after the scene has a real url", () => {
    patchImagineScene({ selectedId: "legs" });
    getImagineScene().setImageUrl("/imagine/legs.jpg");
    expect(getImagineStatus().phase).toBe("idle");
    const html = renderToStaticMarkup(<ImagineSlot />);
    expect(html).toContain("Generated by Grok Imagine");
    expect(html).toContain("/imagine/legs.jpg");
    expect(html).toContain("made-up picture");
  });
});
